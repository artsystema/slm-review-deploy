export function normalizeLanguage(value) {
  return String(value || '').toLowerCase().startsWith('uk') ? 'uk' : 'en';
}

export function localeFor(language) {
  return normalizeLanguage(language) === 'uk' ? 'uk-UA' : 'en-GB';
}

export function hasTranslation(key, language = 'en') {
  return Object.hasOwn(messages[normalizeLanguage(language)], key);
}

export function translate(key, language = 'en', variables = {}) {
  const selected = messages[normalizeLanguage(language)];
  const template = selected[key] ?? messages.en[key] ?? key;
  return String(template).replace(/\{([a-z_]+)\}/gi, (_, name) => String(variables[name] ?? `{${name}}`));
}
